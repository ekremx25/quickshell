#!/usr/bin/env python3
"""Write and apply Hyprland window blur and wobble from Settings → Effects.

The settings are written to ~/.config/hypr/lua/quickshell_effects.lua, which
hyprland.lua loads, so they survive Hyprland reloads and restarts. The same
file is then evaluated live with `hyprctl eval`. Only the Lua config provider
(Hyprland 0.56+) is supported; other providers are left untouched.
"""

from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
import re
import subprocess
import tempfile

BLUR_STYLES = (
    "kawase", "frost", "ripple", "drops", "water", "fluid_jar",
    "prism", "heat_shimmer", "acrylic", "aurora", "haze",
)
HEX_COLOR = re.compile(r"^[0-9a-fA-F]{8}$")
RULES_BEGIN = "-- quickshell:rules-begin"
RULES_END = "-- quickshell:rules-end"


def clamp(value: float, low: float, high: float) -> float:
    return max(low, min(high, value))


def lua_bool(value: bool) -> str:
    return "true" if value else "false"


def lua_number(value: float) -> str:
    return f"{value:.4f}".rstrip("0").rstrip(".")


def parse_bool(raw: str) -> bool:
    return raw.strip().lower() in ("1", "true", "yes", "on")


def color(raw: str, fallback: str) -> str:
    raw = raw.strip().lstrip("#")
    if len(raw) == 6:
        raw += "ff"
    return f"rgba({(raw if HEX_COLOR.match(raw) else fallback).lower()})"


def lua_string(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def secondary_descriptions(config_home: Path) -> list[str]:
    """EDID descriptions of every monitor except the primary role.

    Rules match descriptions, not connectors, so they keep working when cables
    move between ports.
    """
    try:
        monitors = json.loads(subprocess.run(["hyprctl", "monitors", "all", "-j"], capture_output=True,
                                             text=True, timeout=5).stdout)
    except (OSError, subprocess.TimeoutExpired, json.JSONDecodeError):
        return []
    try:
        primary = json.loads((config_home / "quickshell/monitor_runtime.json").read_text()).get("primary", "")
    except (OSError, json.JSONDecodeError, AttributeError):
        primary = ""
    named = [m for m in monitors if isinstance(m, dict) and m.get("name") and m.get("description")]
    if not any(m["name"] == primary for m in named):
        # No role map: treat the monitor at the layout origin as the primary.
        origin = sorted(named, key=lambda m: (m.get("x", 0), m.get("y", 0), m.get("id", 0)))
        primary = origin[0]["name"] if origin else ""
    descriptions = []
    for monitor in named:
        description = str(monitor["description"]).strip()
        if monitor["name"] != primary and "]" not in description and description not in descriptions:
            descriptions.append(description)
    return descriptions


def render_rules(scope: str, descriptions: list[str]) -> str:
    if scope != "primary":
        return ""
    lines = [RULES_BEGIN, "-- Wobble only on the primary monitor."]
    for index, description in enumerate(descriptions, 1):
        lines.append(f"hl.window_rule({{ name = {lua_string(f'quickshell-no-wobble-{index}')}, "
                     f"match = {{ workspace = {lua_string(f'm[desc:{description}]')} }}, no_wobble = true }})")
    lines.append(RULES_END)
    return "\n".join(lines) + "\n"


def rules_block(text: str) -> str:
    start, end = text.find(RULES_BEGIN), text.find(RULES_END)
    return text[start:end] if start != -1 and end != -1 else ""


def render(args: argparse.Namespace, rules: str = "") -> str:
    style = args.style if args.style in BLUR_STYLES else "kawase"
    blur = (
        f"enabled = {lua_bool(parse_bool(args.blur))}, "
        f'variant = "{style}", '
        f"size = {int(clamp(args.size, 1, 30))}, "
        f"passes = {int(clamp(args.passes, 1, 6))}, "
        f'aurora = {{ color1 = "{color(args.aurora1, "29f0a0ff")}", '
        f'color2 = "{color(args.aurora2, "7a4dffff")}" }}'
    )
    wobble = (
        f"enabled = {lua_bool(parse_bool(args.wobble))}, "
        f"intensity = {lua_number(clamp(args.intensity, 0.05, 1.0))}, "
        f"stiffness = {lua_number(clamp(args.stiffness, 50, 600))}, "
        f"damping = {lua_number(clamp(args.damping, 2, 40))}"
    )
    return (
        "-- Generated by Quickshell (Settings → Effects). Do not edit by hand;\n"
        "-- changes made in Quickshell overwrite this file.\n"
        "hl.config({ decoration = {\n"
        f"  blur = {{ {blur} }},\n"
        f"  wobble = {{ {wobble} }},\n"
        "} })\n"
        + rules
    )


def atomic_write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, temporary = tempfile.mkstemp(prefix=f".{path.name}.", dir=path.parent)
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as handle:
            handle.write(text)
        os.replace(temporary, path)
    finally:
        if os.path.exists(temporary):
            os.unlink(temporary)


def config_provider() -> str:
    try:
        info = subprocess.run(["hyprctl", "systeminfo"], capture_output=True, text=True, timeout=5).stdout
    except (OSError, subprocess.TimeoutExpired):
        return ""
    match = re.search(r"configProvider:\s*(\S+)", info)
    return match.group(1) if match else ""


def loaded_by_config(config_home: Path) -> bool:
    """True when the Hyprland Lua config requires quickshell_effects."""
    hypr = config_home / "hypr"
    for path in [hypr / "hyprland.lua", *sorted((hypr / "lua").glob("*.lua"))]:
        if path.name == "quickshell_effects.lua":
            continue
        try:
            if "quickshell_effects" in path.read_text(encoding="utf-8"):
                return True
        except OSError:
            continue
    return False


def autoreload_enabled() -> bool:
    try:
        out = subprocess.run(["hyprctl", "getoption", "misc:disable_autoreload"], capture_output=True,
                             text=True, timeout=5).stdout
    except (OSError, subprocess.TimeoutExpired):
        return False
    return "bool: false" in out or "int: 0" in out


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--blur", default="false")
    parser.add_argument("--style", default="kawase")
    parser.add_argument("--size", type=float, default=9)
    parser.add_argument("--passes", type=float, default=3)
    parser.add_argument("--aurora1", default="29f0a0ff")
    parser.add_argument("--aurora2", default="7a4dffff")
    parser.add_argument("--wobble", default="false")
    parser.add_argument("--intensity", type=float, default=0.2)
    parser.add_argument("--stiffness", type=float, default=200)
    parser.add_argument("--damping", type=float, default=12)
    parser.add_argument("--wobble-scope", choices=("all", "primary"), default="all")
    parser.add_argument("--output", default="")
    parser.add_argument("--no-apply", action="store_true")
    args = parser.parse_args()

    if config_provider() != "lua" and not args.output:
        return 0
    config_home = Path(os.environ.get("XDG_CONFIG_HOME", Path.home() / ".config"))
    target = Path(args.output) if args.output else config_home / "hypr/lua/quickshell_effects.lua"
    try:
        previous = target.read_text(encoding="utf-8")
    except OSError:
        previous = ""
    rules = render_rules(args.wobble_scope, secondary_descriptions(config_home))
    text = render(args, rules)
    if text == previous and not args.output:
        # Hyprland auto-reloads when this file changes, and a reload makes
        # Quickshell apply again. Leaving an unchanged file alone ends that loop.
        return 0
    previous_rules = rules_block(previous)
    atomic_write(target, text)
    if args.no_apply:
        return 0
    if loaded_by_config(config_home) and autoreload_enabled():
        # Hyprland already reloads when this file changes; applying it again
        # here would only run the same settings twice.
        return 0
    if rules_block(text) != previous_rules:
        # Window rules cannot be removed one by one; a reload rebuilds them
        # from the config files, including this one.
        command = ["hyprctl", "reload"]
    else:
        lua_path = str(target).replace("\\", "\\\\").replace('"', '\\"')
        # Re-running only the hl.config part avoids stacking duplicate rules.
        # Starts at hl.config: hyprctl would read the leading "--" comment as a flag.
        config_only = text[text.find("hl.config("):text.find(RULES_BEGIN)]
        command = ["hyprctl", "eval", config_only if rules else f'dofile("{lua_path}")']
    result = subprocess.run(command, capture_output=True, text=True, timeout=10)
    output = (result.stdout + result.stderr).strip()
    if result.returncode != 0 or (output and output != "ok"):
        print(output or f"hyprctl exited with {result.returncode}")
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
